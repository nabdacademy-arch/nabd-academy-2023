-- Director council provisioning audit. Secrets and initial passwords are NEVER stored here.
begin;
create table if not exists public.nabd_council_account_audit (
  id bigint generated by default as identity primary key,
  action text not null check (action in ('create_account','assign_existing','change_membership')),
  actor_user_id uuid references auth.users(id) on delete set null,
  target_user_id uuid references auth.users(id) on delete set null,
  council_code text not null check (council_code in ('trustees','academic','research','students','international','quality','digital','humanitarian')),
  position text check (position in ('member','chair','vice_chair','secretary')),
  active boolean,
  created_at timestamptz not null default now()
);
create index if not exists nabd_council_account_audit_time_idx on public.nabd_council_account_audit(created_at desc);
alter table public.nabd_council_account_audit enable row level security;
revoke all on table public.nabd_council_account_audit from public,anon,authenticated;
grant select on table public.nabd_council_account_audit to authenticated;
create policy nabd_council_audit_admin_read on public.nabd_council_account_audit
  for select to authenticated using ((select public.is_admin()));
comment on table public.nabd_council_account_audit is
  'Server-written council account and membership audit; never contains passwords or recovery secrets.';
commit;