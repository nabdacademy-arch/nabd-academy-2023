"use strict";
const assert=require("node:assert/strict"),{spawn}=require("node:child_process"),{resolve}=require("node:path"),{chromium}=require("playwright");
const pause=ms=>new Promise(r=>setTimeout(r,ms));
async function run(){
 const port=8896,base="http://127.0.0.1:"+port,server=spawn("python3",["-m","http.server",String(port),"--bind","127.0.0.1"],{cwd:resolve(__dirname,".."),stdio:"ignore"});let browser;
 try{
  let ready=false;for(let i=0;i<60;i++){try{ready=(await fetch(base+"/academy.html")).ok;if(ready)break}catch{}await pause(150)}
  assert.ok(ready,"Static source server starts");
  browser=await chromium.launch({headless:true});
  for(const width of [390,1440]){
   const ctx=await browser.newContext({viewport:{width,height:850},reducedMotion:"reduce"});
   await ctx.route(/^https:\/\//,r=>r.abort());
   const page=await ctx.newPage(),chatErrors=[];
   page.on("pageerror",e=>{if(String(e.stack||e.message).includes("nabd-assistant.js"))chatErrors.push(e.message)});
   await page.goto(base+"/academy.html",{waitUntil:"domcontentloaded"});
   await page.locator("#nb-chat-launch").waitFor({timeout:15000});
   assert.equal(await page.locator("#nabd-chat-root").count(),1,"One messenger instance");
   assert.equal(await page.locator("#nb-chat-panel").isVisible(),false,"Starts closed");
   const right=await page.locator("#nb-chat-launch").evaluate(e=>Math.round(e.getBoundingClientRect().right));
   assert.ok(width-right<38,"Launcher fixed to right edge");
   await page.locator("#nb-chat-launch").click();
   assert.ok(await page.locator("#nb-chat-panel").isVisible(),"Click opens dialog");
   assert.equal(await page.locator("#nb-chat-panel").getAttribute("role"),"dialog");
   await page.locator("#nb-chat-input").fill("كيف أتحقق من شهادتي؟");
   await page.locator("#nb-chat-send").click();
   await page.locator(".nb-chat-bot").last().locator(".nb-chat-bubble").waitFor();
   assert.match(await page.locator(".nb-chat-bot").last().innerText(),/الشهادات|التحقق/,"Grounded certificate guidance");
   const links=await page.locator(".nb-chat-bot").last().locator("a").all();
   assert.ok(links.length,"Actual relevant routes are linked");
   assert.ok((await links[0].getAttribute("href")).includes("/index.html#verify"),"Real certificate verification link");
   await page.locator("#nb-chat-input").fill("عندي ألم شديد شخّصني");
   await page.locator("#nb-chat-send").click();
   assert.match(await page.locator(".nb-chat-bot").last().innerText(),/لا يمكن.*تشخيص/,"Medical triage refusal");
   await page.locator("#nb-chat-input").fill("كلمة المرور السرية رقم الهاتف 0599999999");
   await page.locator("#nb-chat-send").click();
   assert.match(await page.locator(".nb-chat-bot").last().innerText(),/البيانات|كلمات مرور|خاصة/,"Privacy warning");
   await page.locator("#nb-chat-ai").click();
   assert.match(await page.locator("#nb-chat-disclosure").innerText(),/للحسابات المسجلة/,"Explicit AI mode disclosure");
   await page.locator("#nb-chat-input").fill("اشرح الدورة الدموية");
   await page.locator("#nb-chat-send").click();
   await page.waitForFunction(()=>document.querySelector("#nb-chat-send")?.disabled===false,{timeout:10000});
   assert.match(await page.locator(".nb-chat-bot").last().innerText(),/سجّل الدخول|سجل الدخول|تمكن/,"AI requires account or reports unavailable");
   await page.locator("#nb-chat-lang").click();
   assert.equal(await page.locator("#nb-chat-panel").getAttribute("dir"),"ltr","English direction independent of page");
   assert.match(await page.locator("#nb-chat-title").innerText(),/NABD Smart Assistant/);
   await page.locator("#nb-chat-guide").click();
   assert.match(await page.locator("#nb-chat-disclosure").innerText(),/not sent to a server/);
   await page.locator("#nb-chat-input").fill("research");
   await page.locator("#nb-chat-send").click();
   assert.match(await page.locator(".nb-chat-bot").last().innerText(),/research network/i);
   await page.locator("#nb-chat-clear").click();
   assert.equal(await page.locator(".nb-chat-msg").count(),1,"Clear resets ephemeral transcript");
   await page.keyboard.press("Escape");assert.equal(await page.locator("#nb-chat-panel").isVisible(),false,"Escape closes dialog");
   const overflow=await page.evaluate(()=>document.documentElement.scrollWidth-innerWidth);
   assert.ok(overflow<=5,"No horizontal overflow "+width+": "+overflow);
   assert.deepEqual(chatErrors,[],"No chat widget errors");
   await ctx.close();
  }
  const ctx=await browser.newContext({viewport:{width:390,height:780},reducedMotion:"reduce"});
  await ctx.route(/^https:\/\//,r=>r.abort());
  const page=await ctx.newPage();
  await page.addInitScript(()=>{window.nabdSupabase={auth:{getUser:async()=>({data:{user:{id:"test-user"}},error:null})},functions:{invoke:async(name,args)=>{window.tutorCalls=(window.tutorCalls||[]).concat([{name,args}]);return {data:{answer:"The heart is a four chambered muscular pump."}}}}};window.NABD_CONFIG={tutorFunction:"smart-processor"}});
  await page.goto(base+"/academy.html",{waitUntil:"domcontentloaded"});
  await page.locator("#nb-chat-launch").click();
  await page.locator("#nb-chat-ai").click();
  await page.locator("#nb-chat-input").fill("Describe the four heart chambers.");
  await page.locator("#nb-chat-send").click();
  await page.waitForFunction(()=>document.querySelector("#nb-chat-send")?.disabled===false);
  assert.match(await page.locator(".nb-chat-bot").last().innerText(),/four chambered/,"AI response is rendered as plain text");
  const calls=await page.evaluate(()=>window.tutorCalls||[]);
  assert.equal(calls.length,1,"One authenticated AI call");
  assert.equal(calls[0].name,"smart-processor","Existing verified function slug");
  assert.equal(calls[0].args.body.language,"ar","Language passed securely");
  await page.locator("#nb-chat-guide").click();
  await page.locator("#nb-chat-input").fill("What courses are available?");
  await page.locator("#nb-chat-send").click();
  assert.equal(await page.evaluate(()=>(window.tutorCalls||[]).length),1,"Guide never invokes AI or backend");
  await ctx.close();
  const nested=await browser.newPage();
  await nested.goto(base+"/atlas/clinical-hub.html",{waitUntil:"domcontentloaded"});
  await nested.locator("#nb-chat-launch").waitFor({timeout:10000});
  await nested.locator("#nb-chat-launch").click();
  await nested.locator("#nb-chat-input").fill("virtual hospital");
  await nested.locator("#nb-chat-send").click();
  assert.match(await nested.locator(".nb-chat-bot").last().locator("a").first().getAttribute("href"),/nabd-2050\.html/,"Nested route links resolve at repository root");
  await nested.close();
  console.log("NABD Messenger browser: desktop/mobile, right position, guide, safety, AI mock, nested URLs PASS");
 }finally{if(browser)await browser.close();server.kill()}
}
run().catch(e=>{console.error(e);process.exitCode=1});
