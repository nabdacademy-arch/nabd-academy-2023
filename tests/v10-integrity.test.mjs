import assert from "node:assert/strict";
import { readFileSync, existsSync, statSync } from "node:fs";
import { Script } from "node:vm";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
const root=resolve(dirname(fileURLToPath(import.meta.url)),"..");
const read=p=>readFileSync(resolve(root,p),"utf8");
const page=read("nabd-v10.html");
const home=read("index.html");
const js=read("assets/js/nabd-v10.js");
const css=read("assets/css/nabd-v10.css");
const homeCss=read("assets/css/nabd-v10-home.css");
let tested=0;
const test=(condition,message)=>{assert.ok(condition,message);tested++};
test(page.includes('lang="ar" dir="rtl"'),"Arabic default and direction");
test(page.includes('id="pathwayGrid"'),"Pathway listing");
test(page.includes('id="systemList"')&&page.includes('id="systemPanel"'),"Interactive systems");
test(page.includes('id="quizPanel"')&&page.includes('id="quizFeedback"'),"Quiz containers");
test(page.includes('id="missionResult"')&&page.includes('id="downloadPlan"'),"Planner export");
test(page.includes('assets/images/founder.jpg'),"Founder portrait");
test(home.includes('id="v10-universe"')&&home.includes('href="nabd-v10.html"'),"Homepage V10 integration");
test(home.includes('id="nabd-unified-campus"')&&home.includes('id="global-research-gateway"'),"Existing routes retained");
test(home.includes("nabd-v10-home.css"),"Launch styles");
test(css.includes("@media(max-width:580px)")&&css.includes("prefers-reduced-motion"),"Mobile and reduced motion");
test(homeCss.includes(".nv10-home"),"Scoped homepage styles");
test(js.includes("function setLanguage(")&&js.includes("documentElement.dir"),"Bilingual switching");
test(js.includes("function generatePlan(")&&js.includes("function downloadPlan("),"Plan and export");
test(js.includes("function showQuizResult(")&&js.includes("quizStep==="),"Full quiz");
test(!/\bfetch\s*\(|XMLHttpRequest|localStorage|sessionStorage|sendBeacon/.test(js),"No network or browser storage");
new Script(js,{filename:"nabd-v10.js"});tested++;
const ids=[...page.matchAll(/\bid="([^"]+)"/g)].map(m=>m[1]);
test(new Set(ids).size===ids.length,"Unique HTML IDs");
const uses=[...js.matchAll(/\bbyId\("([^"]+)"\)/g)].map(m=>m[1]);
test(uses.every(id=>ids.includes(id)),"All JS DOM targets exist");
for(const tag of page.match(/<[^>]+>/g)||[]){if(tag.includes("data-ar=")&&!tag.includes("data-en="))throw Error("Missing English translation: "+tag.slice(0,110));}
tested++;
const refs=[...page.matchAll(/\b(?:href|src)="([^"]+)"/g)].map(m=>m[1]);
const routes=[...js.matchAll(/\bhref:"([^"]+)"/g)].map(m=>m[1]);
for(const href of [...refs,...routes]){if(href.startsWith("#")||/^(https?:|mailto:|data:)/.test(href))continue;const p=href.split("?")[0].split("#")[0];if(!p)continue;const target=resolve(root,p);test(existsSync(target),"Missing linked file or route: "+href);if(p.endsWith("/"))test(statSync(target).isDirectory()&&existsSync(resolve(target,"index.html")),"Missing index in directory route: "+href);}
console.log("NABD V10 checks passed: "+tested+" assertions.");
